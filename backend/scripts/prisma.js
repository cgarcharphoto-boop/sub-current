// Runs the Prisma CLI against the right database provider.
//
// prisma/schema.prisma is written for SQLite (local dev, tests, demo). When
// DATABASE_URL is a Postgres URL, this writes prisma/schema.postgres.prisma
// (same models, provider switched) and points the CLI at it. Prisma can't
// pick a provider at runtime, so the switch happens here, at generate time,
// which Vercel runs on every build via postinstall.
//
// Usage: node scripts/prisma.js <prisma args...>   e.g. `generate`, `db push`
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import 'dotenv/config';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'prisma/schema.prisma');
const url = process.env.DATABASE_URL || '';
const isPostgres = /^postgres(ql)?:\/\//.test(url);

let schema = base;
if (isPostgres) {
  schema = path.join(root, 'prisma/schema.postgres.prisma');
  const src = fs.readFileSync(base, 'utf8');
  const out = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
  if (out === src) throw new Error('Could not switch provider in prisma/schema.prisma');
  fs.writeFileSync(schema, '// GENERATED by scripts/prisma.js from schema.prisma. Do not edit.\n' + out);
}

const args = process.argv.slice(2);
console.log(`[prisma] ${isPostgres ? 'postgresql' : 'sqlite'}: prisma ${args.join(' ')}`);
execFileSync(path.join(root, 'node_modules/.bin/prisma'), [...args, '--schema', schema], { stdio: 'inherit', env: process.env });
